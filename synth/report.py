"""Turn synth/out/stat_hier.txt into docs/budget.md (per-module cells and area vs the hand estimates)."""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
STAT = os.path.join(HERE, "out", "stat_hier.txt")
OUT = os.path.join(HERE, "..", "docs", "budget.md")

BUDGET_UM2 = 549_700  # 6x4 tiles at 60% placement density, from the research doc
PLANNING_FACTOR = 1.3

# Hand estimates from the research doc's bottom-up method, for comparison.
HAND = {
    "weft_pmem": ("Program memory 128 x 16, flops + read mux", 166_440),
    "weft_core": ("Core: PC, decoder, ALU, flags, pin registers, cycle counter", 10_000),
    "weft_regfile": ("Register file 8 x 16, 2 read ports", 11_759),
    "weft_host_spi": ("Host SPI port", 4_000),
    "weft_fifo": ("FIFO 4 x 16 (each)", 5_200),
    "weft_crc": ("CRC/LFSR 16-bit, programmable", 2_540),
    "weft_timer": ("Bit timer: period, counter, tick", 3_081),
    "weft_sync": ("Synchronizers, 16 inputs x 3 flops", 2_352),
    "tt_um_fuzzylogique_weft": ("Top-level glue", 0),
}


def parse(path):
    mods = {}
    cur = None
    for line in open(path):
        m = re.match(r"=== (.+) ===", line.strip())
        if m:
            cur = m.group(1)
            name = re.sub(r"^\$paramod\$[0-9a-f]+\\", "", cur)  # $paramod$<hash>\name
            name = re.sub(r"^\$paramod\\", "", name)            # $paramod\name\PARAM=...
            name = name.split("\\")[0].lstrip("\\")
            mods[cur] = {"name": name, "cells": 0, "area": 0.0, "seq": 0.0}
            continue
        if cur is None:
            continue
        m = re.match(r"\s+(\d+)\s+([0-9.E+]+)\s+cells", line)
        if m and mods[cur]["cells"] == 0:
            mods[cur]["cells"] = int(m.group(1))
        m = re.search(r"Chip area for (?:top )?module '.+': ([0-9.]+)$", line.rstrip())
        if m:
            mods[cur]["area"] = float(m.group(1))
        m = re.search(r"sequential elements: ([0-9.]+)", line)
        if m:
            mods[cur]["seq"] = float(m.group(1))
    total = None
    for line in open(path):
        m = re.search(r"Chip area for top module '.+': ([0-9.]+)$", line.rstrip())
        if m:
            total = float(m.group(1))
    flops = 0
    for line in open(os.path.join(HERE, "out", "stat_flat.txt")):
        m = re.search(r"^\s+(\d+)\s+[0-9.E+]+\s+sg13\w+_dfrbpq_1", line)
        if m:
            flops = int(m.group(1))
    return mods, total, flops


def main():
    mods, total, flops = parse(STAT)
    rows = []
    seen = {}
    for key, m in mods.items():
        if m["name"] == "design hierarchy":
            continue
        n = m["name"]
        inst = 2 if n == "weft_fifo" else 1
        if n in seen:
            continue
        seen[n] = True
        desc, hand = HAND.get(n, (n, 0))
        rows.append((n, desc, inst, m["cells"], m["area"], hand))
    rows.sort(key=lambda r: -r[4] * r[2])
    lines = [
        "# Area budget\n",
        "*Generated by `make synth` (synth/report.py) from Yosys + ABC mapped to the IHP CMOS5L liberty "
        "`sg13cmos5l_stdcell_typ_1p20V_25C.lib`. Pre-layout: expect LibreLane to add 20% to 50% for buffering, "
        "clock tree and hold fixing. Hand estimates use the bottom-up method from the research doc's Numbers tab.*\n",
        f"Budget: 6x4 tiles at 60% density = {BUDGET_UM2:,} µm² of standard cells. Planning rule: keep the "
        f"synthesized total times {PLANNING_FACTOR} under 75% of that.\n",
        "| Module | What | Instances | Cells (each) | Area µm² (each) | Area µm² (all) | % of budget | Hand estimate µm² |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for n, desc, inst, cells, area, hand in rows:
        lines.append(f"| `{n}` | {desc} | {inst} | {cells:,} | {area:,.0f} | {area * inst:,.0f} | {100 * area * inst / BUDGET_UM2:.1f}% | {hand:,} |")
    lines.append(f"| **total** | flattened design | | | | **{total:,.0f}** | **{100 * total / BUDGET_UM2:.1f}%** | ~215,000 |")
    lines.append("")
    lines.append(f"- Flip-flops: {flops:,} (`dfrbpq_1`, {flops * 48.99:,.0f} µm², {100 * flops * 48.99 / total:.0f}% of the area). "
                 f"{2048:,} of them are the program memory.")
    lines.append(f"- With the {PLANNING_FACTOR} planning factor: {total * PLANNING_FACTOR:,.0f} µm² = {100 * total * PLANNING_FACTOR / BUDGET_UM2:.0f}% of the budget. "
                 f"The 75% ceiling is {0.75 * BUDGET_UM2:,.0f} µm².")
    lines.append("- Logic excluding program memory: "
                 f"{total - next(r[4] for r in rows if r[0] == 'weft_pmem'):,.0f} µm². Halving the memory to 64 words "
                 f"(`PMEM_AW = 6`) would save about {next(r[4] for r in rows if r[0] == 'weft_pmem') / 2:,.0f} µm².")
    lines.append("- Measured numbers from the Tiny Tapeout `gds` action (utilization, slack after place and route) go here once the first run completes.")
    lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: total {total:,.0f} µm², {100 * total / BUDGET_UM2:.1f}% of budget")


if __name__ == "__main__":
    main()
