"""Generate formal/uart_tx_rom.vh: sw/programs/uart_tx.asm assembled with BIT=4 as a case ROM."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "sw"))
from weft import asm  # noqa: E402

prog = asm.assemble_file(os.path.join(HERE, "..", "sw", "programs", "uart_tx.asm"), depth=16, symbols={"BIT": 4})
lines = [f"      4'd{a}: instr = 16'h{w:04x};  // {asm.disassemble(w)}" for a, w in enumerate(prog.words)]
out = os.path.join(HERE, "uart_tx_rom.vh")
with open(out, "w") as f:
    f.write("// Generated by formal/gen_roms.py from sw/programs/uart_tx.asm with BIT=4. Do not edit.\n")
    f.write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(prog.words)} words")
